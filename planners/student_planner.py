# ---------------------------------------------------------------------------
# Tuning parameters
# ---------------------------------------------------------------------------
NORMAL_LIMITS = SpeedLimits(
    max_accel_mps2=2.0,           # was 1.5; 2.0 is the most the simulator's controller will apply
    comfort_decel_mps2=2.0,
    max_decel_mps2=3.0,
    max_jerk_mps3=6.0,            # was 4.0; lets acceleration/braking ramp up faster (quicker reactions)
    max_lateral_accel_mps2=1.8,
    idm_standstill_gap_m=2.5,
    idm_time_gap_s=1.2,           # was 1.5; follows a lead car a bit closer, still a safe 1.2 s gap
)
FIRM_LIMITS = SpeedLimits(
    max_accel_mps2=2.0,
    comfort_decel_mps2=3.0,
    max_decel_mps2=6.0,
    max_jerk_mps3=15.0,
    max_lateral_accel_mps2=1.8,
)

CHECK_HORIZON_S        = 8.0    # predict road users 8 s into the future when validating
STOP_SIGN_WAIT_S       = 2.0    # how long to pause at a stop sign
LANE_CHANGE_COOLDOWN_S = 3.0    # minimum time between lane changes (avoid ping-pong)
CROSSING_BUFFER_S      = 1.5    # extra time buffer for actors crossing our path
CROSSWALK_YIELD_DIST_M = 30.0   # start watching for pedestrians this far before a crosswalk
PED_LATERAL_RANGE_M    = 6.0    # how far left/right a pedestrian must be to concern us
PED_CORRIDOR_M         = 3.5    # a pedestrian this close sideways is in (or at the edge of) our path
PED_REACH_TIME_S       = 4.0    # yield to a pedestrian walking toward our path if it gets there within this
SPEED_LIMIT_MARGIN     = 0.97   # cruise at 97 % of the posted limit (never above it)


def cruise_speed(obs) -> float:
    """Target cruise speed: the posted limit minus a small margin, but never
    slower than the scenario's desired speed allows (and never above the limit)."""
    return min(obs.speed_limit_mps, max(obs.desired_speed_mps, SPEED_LIMIT_MARGIN * obs.speed_limit_mps))


def find_constraining_lead(lane, actors, ego_speed_mps: float,
                           limits: SpeedLimits = NORMAL_LIMITS) -> Optional[Lead]:
    """Like ``find_lead``, but looks at EVERY road user ahead in the lane, not
    only the nearest one, and returns the one that forces us to slow down most.

    Example: a car at 8 m/s is ahead of us and a truck at 4 m/s is ahead of
    that car.  The car will have to slow down for the truck, so we should start
    slowing down for the truck now instead of braking hard later.

    A road user further ahead is treated as if it were closer by the space the
    vehicles in between take up (their length + a standstill gap each)."""
    ego_front = lane.ego_s_m + EGO_REAR_AXLE_TO_FRONT_M
    ahead = []
    for a in actors:
        s, d = actor_position_on_lane(lane, a)
        if s <= lane.ego_s_m or not is_in_lane(lane, a, s, d):
            continue
        ahead.append((s - 0.5 * a.length_m, a, s))
    ahead.sort(key=lambda item: item[0])

    best, best_accel = None, math.inf
    occupied = 0.0                       # space taken by the vehicles in between
    v = max(ego_speed_mps, 0.0)
    two_sqrt_ab = 2.0 * math.sqrt(limits.max_accel_mps2 * limits.comfort_decel_mps2)
    for rear, a, s in ahead:
        v_lead = speed_along_lane(lane, a, s)
        lead = Lead(a.actor_id, rear - occupied - ego_front, v_lead, rear - occupied)
        # Intelligent Driver Model: how hard would this road user make us brake?
        s_star = max(limits.idm_standstill_gap_m,
                     limits.idm_standstill_gap_m + v * limits.idm_time_gap_s + v * (v - v_lead) / two_sqrt_ab)
        accel = limits.max_accel_mps2 * (1.0 - (s_star / max(lead.gap_m, 0.1)) ** 2)
        if accel < best_accel:
            best, best_accel = lead, accel
        occupied += a.length_m + limits.idm_standstill_gap_m
    return best


def first_collision_lane_aware(obs, t, x, y, heading, ignore_ids, crossing_time_buffer_s: float = 0.0):
    """Like planner_tools.first_collision, but vehicles that are driving IN one
    of our lanes (current / left / right) are predicted to FOLLOW THAT LANE
    (curving with the road) instead of driving in a straight line.

    Why: on a curve, a straight-line prediction of a car in the next lane cuts
    across our lane and causes false "collision ahead" alarms and needless hard
    braking.  Pedestrians and crossing traffic still use the straight-line
    prediction (with the crossing time buffer)."""
    t, x, y, heading = (np.asarray(v, float) for v in (t, x, y, heading))
    followers = {}
    for a in obs.actors:
        if a.kind == "pedestrian" or a.actor_id in ignore_ids:
            continue
        for lane in obs.lanes.values():
            s, d = actor_position_on_lane(lane, a)
            # The lane map starts ~15 m behind us; also accept cars a bit before
            # its start (the lane is extended straight back from its first point).
            if not -30.0 <= s <= lane.centerline.length_m or abs(d) > 0.5 * lane.width_m + 0.5:
                continue
            lane_heading = float(reference_state(lane.centerline, max(s, 0.0))[2])
            if abs(wrap_angle(a.heading_rad - lane_heading)) < math.radians(20.0):
                followers[a.actor_id] = (a, lane, s, d)
                break

    best = first_collision(t, x, y, heading, obs.actors, set(ignore_ids) | set(followers),
                           crossing_time_buffer_s=crossing_time_buffer_s)

    cx = x + EGO_CENTER_OFFSET_M * np.cos(heading)
    cy = y + EGO_CENTER_OFFSET_M * np.sin(heading)
    for a, lane, s, d in followers.values():
        v = max(speed_along_lane(lane, a, s), 0.0)
        s_pred = s + v * t
        ax, ay = frenet_to_cartesian(lane.centerline, s_pred, np.full_like(t, d))
        ah = np.asarray(reference_state(lane.centerline, s_pred)[2], float)
        near = np.hypot(cx - ax, cy - ay) < 0.5 * (EGO_LENGTH_M + a.length_m) + 4.0
        if not near.any():
            continue
        margin = SAFETY_MARGIN_M.get(a.kind, 0.3)
        hit = boxes_overlap_many(cx, cy, heading, EGO_LENGTH_M + 1.0, EGO_WIDTH_M + 2 * margin,
                                 ax, ay, ah, a.length_m, a.width_m)
        idx = np.flatnonzero(hit & near)
        if idx.size and (best is None or t[idx[0]] < best[0]):
            k = int(idx[0])
            best = (float(t[k]), a.actor_id, float(x[k]), float(y[k]))
    return best


def pedestrian_concerns_us(actor) -> bool:
    """True if a pedestrian is in our path, about to enter it, or waiting at the
    kerb right beside it.  A pedestrian that has already crossed our path and is
    walking away no longer stops us (so we move off sooner)."""
    y, vy = actor.y_m, actor.vy_mps
    if abs(y) > PED_LATERAL_RANGE_M:
        return False
    if abs(y) < PED_CORRIDOR_M:
        return True                                   # in our path
    if actor.speed_mps < 0.2:
        return True                                   # standing at the kerb: may step out, so yield
    moving_toward = y * vy < 0.0
    if not moving_toward:
        return False                                  # walking away from our path
    time_to_path = (abs(y) - PED_CORRIDOR_M) / max(abs(vy), 0.1)
    return time_to_path < PED_REACH_TIME_S


# ---------------------------------------------------------------------------
# Internal data class
# ---------------------------------------------------------------------------
@dataclass
class Candidate:
    """One planned trajectory option evaluated by the planner."""
    name:        str
    lane_name:   str
    trajectory:  Trajectory
    lane:        object
    lead:        Optional[Lead] = None
    stop_reason: Optional[str]  = None
    valid:       bool           = True
    reason:      str            = ""
    cost:        float          = math.inf
    conflict_s:  Optional[float] = None   # lane s of first predicted conflict
    potential_travel_m: Optional[float] = None   # lane changes: distance possible once in the new lane


# ---------------------------------------------------------------------------
# Main planner class
# ---------------------------------------------------------------------------
class StudentPlanner:
    """
    AV trajectory planner for Project B.

    The simulator calls ``plan(observation)`` at 20 Hz.
    Returns a ``Trajectory`` with:
        t_s       – time stamps  [0.0, 0.1, …, 4.0]
        x_m, y_m  – rear-axle positions in the ego frame (x = forward, y = right)
        speed_mps – desired speed at each time stamp
    """

    def __init__(self) -> None:
        self.t: np.ndarray = time_grid(horizon_s=4.0, dt_s=0.1)

        # State carried between planning cycles
        self.target_lane_id:        Optional[str]   = None   # lane change in progress
        self.last_change_time_s:    float           = -math.inf
        self.stop_sign_done:        set             = set()
        self.stop_sign_wait_start:  Optional[float] = None

    # ===================================================================
    # Public interface (called by the simulator)
    # ===================================================================
    def plan(self, obs) -> Trajectory:
        """
        Main planning loop called at 20 Hz.

        Parameters
        ----------
        obs : Observation
            Current sensor snapshot (see simulator/observation.py).

        Returns
        -------
        Trajectory
            The chosen trajectory for the next 4 seconds.
        """
        current_lane = obs.lanes["current"]

        # ---- 1. Finish or abort a lane change ----
        if self.target_lane_id is not None:
            if (current_lane.lane_id == self.target_lane_id
                    and abs(current_lane.ego_d_m) < 0.5):
                self.target_lane_id      = None
                self.last_change_time_s  = obs.time_s     # reset cooldown

        # ---- 2. Find where we must stop for traffic law ----
        stop_s, stop_reason = self._traffic_control_stop(obs)

        # ---- 3. Check crosswalks for pedestrians ----
        crosswalk_stop_s = self._crosswalk_yield_distance(obs)
        if crosswalk_stop_s is not None and (stop_s is None or crosswalk_stop_s < stop_s):
            stop_s      = crosswalk_stop_s
            stop_reason = "pedestrian near crosswalk"

        # ---- 4. Build candidate trajectories ----
        candidates = self._make_candidates(obs, NORMAL_LIMITS, stop_s, stop_reason)

        # ---- 5. Validate each candidate (collision check) ----
        for c in candidates:
            self._validate(obs, c)

        # ---- 6. Add a "stop-before-conflict" candidate if cruise is blocked ----
        cruise = next(
            (c for c in candidates if c.name == "cruise" and c.lane_name == "current"),
            None,
        )
        if cruise is not None and not cruise.valid and cruise.conflict_s is not None:
            conflict_stop = self._conflict_stop_distance(obs, cruise)
            extra = self._make_stop_candidate(
                obs, current_lane, conflict_stop, "conflict ahead", NORMAL_LIMITS
            )
            if extra is not None:
                self._validate(obs, extra)
                candidates.append(extra)

        # ---- 7. Score valid candidates ----
        for c in candidates:
            self._score(obs, c)

        valid = [c for c in candidates if c.valid]

        # ---- 8. If nothing is safe, try firmer braking ----
        emergency = False
        if not valid:
            firm_candidates = self._make_candidates(
                obs, FIRM_LIMITS, stop_s, stop_reason, lanes=("current",)
            )
            if cruise is not None and cruise.conflict_s is not None:
                extra = self._make_stop_candidate(
                    obs, current_lane,
                    self._conflict_stop_distance(obs, cruise),
                    "conflict ahead", FIRM_LIMITS,
                )
                if extra is not None:
                    firm_candidates.append(extra)
            for c in firm_candidates:
                self._validate(obs, c)
                self._score(obs, c)
            valid      = [c for c in firm_candidates if c.valid]
            candidates += firm_candidates
            emergency   = True

        # ---- 9. Select best candidate (or emergency full-stop) ----
        if valid:
            best = min(valid, key=lambda c: c.cost)
        else:
            best      = self._emergency_full_stop(obs)
            emergency = True
            candidates.append(best)

        # ---- 10. Update lane-change state ----
        if best.lane_name != "current" and self.target_lane_id is None:
            self.target_lane_id = best.lane.lane_id
        elif (best.lane_name == "current"
              and self.target_lane_id is not None
              and best.lane.lane_id != self.target_lane_id):
            self.target_lane_id = None     # lane change aborted

        # ---- 11. Annotate and return ----
        traj           = best.trajectory
        traj.behavior  = self._behavior_label(obs, best, emergency)
        traj.notes     = self._notes(best, candidates)
        traj.alternatives = []
        for c in candidates:
            if c is not best:
                c.trajectory.rejected = not c.valid
                traj.alternatives.append(c.trajectory)
        return traj

    # ===================================================================
    # Candidate construction
    # ===================================================================
    def _make_candidates(
        self,
        obs,
        limits: SpeedLimits,
        stop_s: Optional[float],
        stop_reason: Optional[str],
        lanes: Tuple[str, ...] = ("current", "left", "right"),
    ) -> List[Candidate]:
        """Build one cruise candidate per accessible lane, plus a stop-line candidate."""
        out: List[Candidate] = []
        current = obs.lanes["current"]
        near_junction = any(
            j.entry_distance_m < 25.0 and j.exit_distance_m > 0.0
            for j in obs.junctions
        )

        for name in lanes:
            lane = obs.lanes.get(name)
            if lane is None:
                continue

            # Only change lanes when it is legal, not too close to a junction,
            # and not immediately after a previous change.
            if name != "current":
                if not lane.change_allowed or near_junction:
                    continue
                if (obs.time_s - self.last_change_time_s < LANE_CHANGE_COOLDOWN_S
                        and self.target_lane_id is None):
                    continue

            lead = find_constraining_lead(lane, obs.actors, obs.ego.speed_mps, limits)

            target_lead = lead

            # When changing lanes our current-lane lead still constrains us
            # until we are fully in the new lane (safety: never speed up into
            # the back of the vehicle we are leaving).
            if name != "current":
                own_lead = find_lead(current, obs.actors)
                if own_lead is not None and (
                    lead is None or own_lead.gap_m < lead.gap_m
                ):
                    lead = own_lead

            cand = self._make_cruise_candidate(
                obs, lane, name, lead, stop_s, stop_reason, limits
            )

            # For SCORING a lane change, use the speed we will reach once we
            # are in the new lane (its own traffic only).  Without this, a lane
            # change looked no faster than staying behind a cyclist or slow
            # truck, so the car never overtook, even with an empty lane.
            if name != "current":
                s_free, _, _ = speed_profile(
                    self.t, obs.ego.speed_mps, obs.ego.acceleration_mps2, cruise_speed(obs),
                    lane=lane, stop_s_m=stop_s, lead=target_lead, limits=limits,
                )
                cand.potential_travel_m = float(s_free[-1])
            out.append(cand)

        # Yield/stop-line candidate for the current lane
        line = next(
            (sl for sl in obs.stop_lines
             if sl.distance_m - EGO_REAR_AXLE_TO_FRONT_M > -0.5),
            None,
        )
        if line is not None and line.distance_m < 80.0 and stop_s is None:
            reason = "yield line" if line.control is None else "stop line"
            dist   = line.distance_m - EGO_REAR_AXLE_TO_FRONT_M - 1.0
            c = self._make_stop_candidate(obs, current, dist, reason, limits)
            if c is not None:
                out.append(c)

        return out

    def _make_cruise_candidate(
        self, obs, lane, name: str, lead, stop_s, stop_reason, limits
    ) -> Candidate:
        s_rel, v, a = speed_profile(
            self.t,
            obs.ego.speed_mps,
            obs.ego.acceleration_mps2,
            cruise_speed(obs),
            lane=lane,
            stop_s_m=stop_s,
            lead=lead,
            limits=limits,
        )
        d    = self._lateral(obs, lane, s_rel, changing=(name != "current"))
        traj = build_trajectory(lane, self.t, s_rel, d, v, a)
        return Candidate(
            name="cruise",
            lane_name=name,
            trajectory=traj,
            lane=lane,
            lead=lead,
            stop_reason=stop_reason if stop_s is not None else None,
        )

    def _make_stop_candidate(
        self, obs, lane, stop_rear_axle: float, reason: str, limits
    ) -> Optional[Candidate]:
        """Stop with the rear axle at most ``stop_rear_axle`` metres ahead."""
        if stop_rear_axle < -0.5:
            return None
        lead  = find_constraining_lead(lane, obs.actors, obs.ego.speed_mps, limits)
        s_rel, v, a = speed_profile(
            self.t,
            obs.ego.speed_mps,
            obs.ego.acceleration_mps2,
            cruise_speed(obs),
            lane=lane,
            stop_s_m=max(stop_rear_axle, 0.0),
            lead=lead,
            limits=limits,
        )
        d    = self._lateral(obs, lane, s_rel, changing=False)
        traj = build_trajectory(lane, self.t, s_rel, d, v, a)
        return Candidate(
            name="stop",
            lane_name="current",
            trajectory=traj,
            lane=lane,
            lead=lead,
            stop_reason=reason,
        )

    def _emergency_full_stop(self, obs) -> Candidate:
        """Brake as hard as allowed when no other option is safe."""
        lane  = obs.lanes["current"]
        s_rel, v, a = speed_profile(
            self.t,
            obs.ego.speed_mps,
            obs.ego.acceleration_mps2,
            0.0,
            lane=lane,
            stop_s_m=0.0,
            limits=SpeedLimits(max_decel_mps2=6.0, max_jerk_mps3=30.0),
        )
        d    = self._lateral(obs, lane, s_rel, changing=False)
        traj = build_trajectory(lane, self.t, s_rel, d, v, a)
        return Candidate(
            name="full_brake",
            lane_name="current",
            trajectory=traj,
            lane=lane,
            stop_reason="no safe option",
            valid=True,
            cost=0.0,
        )

    # ===================================================================
    # Lateral motion (smooth quintic polynomial)
    # ===================================================================
    def _lateral(self, obs, lane, s_rel: np.ndarray, changing: bool) -> np.ndarray:
        """
        Quintic lateral profile from the current offset back to the lane centre.

        The steering is bounded implicitly: the profile is designed so that the
        peak lateral acceleration stays within ±1.0 m/s² for lane changes and
        ±1.5 m/s² for lane keeping, which keeps the steering angle well within
        the competition limit at all reasonable speeds.
        """
        heading_lane = float(reference_state(lane.centerline, lane.ego_s_m)[2])
        # Initial lateral slope in the ego frame (0 heading = straight ahead)
        slope0  = math.tan(max(-1.0, min(1.0, -heading_lane)))
        v       = max(obs.ego.speed_mps, 2.0)
        offset  = abs(lane.ego_d_m)

        if changing:
            # Lane change: allow up to 1.0 m/s² lateral acceleration
            t_go   = max(2.0, math.sqrt(5.77 * offset / 1.0))
            length = max(20.0, v * t_go)
        else:
            # Lane keep: allow up to 1.5 m/s² lateral acceleration
            t_go   = max(1.5, math.sqrt(5.77 * offset / 1.5))
            length = max(6.0, v * t_go)

        return lateral_profile(lane.ego_d_m, slope0, 0.0, length, s_rel)

    # ===================================================================
    # Traffic law: stop at signals, stop signs
    # ===================================================================
    def _traffic_control_stop(self, obs) -> Tuple[Optional[float], Optional[str]]:
        """
        Return (stop_distance, reason) for the nearest controlling stop line,
        or (None, None) if we may proceed.

        Handles:
          • Red lights  – always stop
          • Yellow lights – stop if comfortable; go if already too close
          • Stop signs   – decelerate, wait 2 s, then proceed when clear
        """
        for line in obs.stop_lines:
            front_dist = line.distance_m - EGO_REAR_AXLE_TO_FRONT_M
            if front_dist < -0.5:
                continue   # already past this line

            stop_at = front_dist - 1.0   # rear-axle target (1 m before line)

            # ---- Signals ----
            if line.control == "signal":
                state = line.signal_state
                v     = obs.ego.speed_mps

                if state == "RED":
                    # Already through the line at speed → clear it rather than slam brakes
                    if front_dist < 0.5 and v > 3.0:
                        continue
                    return max(stop_at, 0.0), "red light"

                if state == "YELLOW":
                    # Only stop if we can do so comfortably
                    needed = v * v / (2.0 * max(stop_at, 0.1))
                    if needed > NORMAL_LIMITS.max_decel_mps2:
                        continue   # too close: go through
                    return max(stop_at, 0.0), "yellow light"

            # ---- Stop signs ----
            if line.control == "stop_sign":
                if line.stop_line_id in self.stop_sign_done:
                    continue   # already served this stop sign

                # Decelerate to the line; once stopped, wait STOP_SIGN_WAIT_S seconds
                if front_dist < 4.0 and obs.ego.speed_mps < 0.1:
                    if self.stop_sign_wait_start is None:
                        self.stop_sign_wait_start = obs.time_s
                    waited = obs.time_s - self.stop_sign_wait_start
                    if waited >= STOP_SIGN_WAIT_S:
                        self.stop_sign_done.add(line.stop_line_id)
                        self.stop_sign_wait_start = None
                        continue   # done waiting, now go

                return max(stop_at, 0.0), "stop sign"

        return None, None

    # ===================================================================
    # Crosswalk pedestrian detection
    # ===================================================================
    def _crosswalk_yield_distance(self, obs) -> Optional[float]:
        """
        If a pedestrian is detected near an upcoming crosswalk, return the
        distance at which we should stop.  Returns None if no yield needed.
        """
        for cw_start, cw_end in obs.crosswalks:
            # Only look at crosswalks that are coming up ahead of us
            if cw_start > CROSSWALK_YIELD_DIST_M or cw_end < -5.0:
                continue

            for actor in obs.actors:
                if actor.kind != "pedestrian":
                    continue

                # Is the pedestrian in, entering, or waiting beside our path?
                if not pedestrian_concerns_us(actor):
                    continue

                # Is the pedestrian longitudinally near the crosswalk?
                in_crosswalk = cw_start - 5.0 <= actor.x_m <= cw_end + 5.0
                if not in_crosswalk:
                    continue

                # Yield 2 m before the crosswalk start
                stop_dist = cw_start - EGO_REAR_AXLE_TO_FRONT_M - 2.0
                return max(stop_dist, 0.0)

        return None

    # ===================================================================
    # Collision validation
    # ===================================================================
    def _validate(self, obs, c: Candidate) -> None:
        """
        Mark candidate invalid if the trajectory collides with any predicted
        road user over the extended CHECK_HORIZON_S window.

        Lane changes are additionally checked for adequate gaps in the target
        lane (front and rear).
        """
        t, x, y, h = extend_trajectory(c.lane, c.trajectory, CHECK_HORIZON_S)

        # Vehicles behind us in our own lane heading the same way may tailgate;
        # ignore them when validating our own trajectory.
        ignore: set = set()
        current = obs.lanes["current"]
        for a in obs.actors:
            s, d = actor_position_on_lane(current, a)
            if (c.lane_name == "current"
                    and s < current.ego_s_m
                    and abs(d) < 0.5 * current.width_m
                    and speed_along_lane(current, a, s) > 0.5):
                ignore.add(a.actor_id)

        hit = first_collision_lane_aware(
            obs, t, x, y, h, ignore,
            crossing_time_buffer_s=CROSSING_BUFFER_S,
        )
        if hit is not None:
            c.valid      = False
            c.reason     = f"collision #{hit[1]} @{hit[0]:.1f}s"
            # Store where along the lane the conflict happens (for conflict-stop candidate)
            c.conflict_s = c.lane.ego_s_m + self._path_distance_at(t, x, y, hit[0])
            return

        # Additional gap check for lane changes
        if c.lane_name != "current":
            gap_issue = self._lane_change_gap_check(obs, c.lane)
            if gap_issue:
                c.valid  = False
                c.reason = gap_issue

    @staticmethod
    def _path_distance_at(t, x, y, t_hit: float) -> float:
        """Distance along (x, y) at time t_hit."""
        seg       = np.hypot(np.diff(x), np.diff(y))
        travelled = np.concatenate(([0.0], np.cumsum(seg)))
        return float(np.interp(t_hit, t, travelled))

    @staticmethod
    def _lane_change_gap_check(obs, target_lane) -> str:
        """
        Return a non-empty reason string if there is not enough room to merge
        into ``target_lane``, empty string if the merge is safe.
        """
        v_ego = obs.ego.speed_mps
        for a in obs.actors:
            s, d = actor_position_on_lane(target_lane, a)
            if abs(d) > 0.5 * target_lane.width_m + 0.5:
                continue   # actor is not in the target lane

            ahead = s - target_lane.ego_s_m
            v_a   = speed_along_lane(target_lane, a, s)

            if ahead >= 0.0:
                # Actor ahead of us in the target lane
                gap    = ahead - 0.5 * a.length_m - EGO_REAR_AXLE_TO_FRONT_M
                needed = max(6.0, 1.0 * v_ego + 2.0 * max(v_ego - v_a, 0.0))
                if gap < needed:
                    return f"front gap {gap:.0f}/{needed:.0f} m"
            else:
                # Actor behind us in the target lane
                gap    = -ahead - 0.5 * a.length_m - 0.8
                needed = max(6.0, 1.0 * v_a + 3.0 * max(v_a - v_ego, 0.0))
                if gap < needed:
                    return f"rear gap {gap:.0f}/{needed:.0f} m"

        return ""

    # ===================================================================
    # Conflict-stop helper
    # ===================================================================
    def _conflict_stop_distance(self, obs, cruise: Candidate) -> float:
        """
        Rear-axle distance at which to stop, chosen to be 2 m before the
        predicted conflict point but never past an upcoming stop/yield line.
        """
        stop = cruise.conflict_s - obs.lanes["current"].ego_s_m - 2.0
        for line in obs.stop_lines:
            line_stop = line.distance_m - EGO_REAR_AXLE_TO_FRONT_M - 1.0
            if line_stop > -0.5:
                return min(stop, line_stop)
        return stop

    # ===================================================================
    # Cost function
    # ===================================================================
    def _score(self, obs, c: Candidate) -> None:
        """
        Assign a scalar cost to candidate ``c``.

        Lower cost = preferred.  Components:
          • Progress: fraction of ideal 4-second travel distance not covered
          • Lane change penalty:  +0.05
          • Off-route penalty:    +0.10
          • Lane-change abandon:  +0.40 (don't abort a started lane change)
          • Harsh braking:        +0.05 × max|a| / 3 m/s²
          • Pedestrian caution:   +0.20 near a crosswalk
        """
        traj   = c.trajectory
        ideal  = max(cruise_speed(obs) * traj.t_s[-1], 1.0)
        travel = float(np.sum(np.hypot(np.diff(traj.x_m), np.diff(traj.y_m))))
        if c.potential_travel_m is not None:
            travel = max(travel, c.potential_travel_m)     # credit a lane change for the faster lane
        cost   = max(0.0, (ideal - travel) / ideal)        # progress lost

        if c.lane_name != "current":
            cost += 0.05                                   # slight preference for staying in lane
        if not c.lane.is_route_lane:
            cost += 0.10                                   # keep to the route
        if (self.target_lane_id is not None
                and c.lane.lane_id != self.target_lane_id):
            cost += 0.40                                   # don't abandon a lane change midway

        # Harsh braking penalty
        cost += 0.05 * float(np.max(np.abs(traj.acceleration_mps2))) / 3.0

        # Penalty for being near a crosswalk with a pedestrian close by
        for cw_start, cw_end in obs.crosswalks:
            if 0.0 < cw_start < CROSSWALK_YIELD_DIST_M:
                for actor in obs.actors:
                    if actor.kind == "pedestrian" and pedestrian_concerns_us(actor):
                        cost += 0.20
                        break

        c.cost = cost

    # ===================================================================
    # Debug / display helpers
    # ===================================================================
    def _behavior_label(self, obs, best: Candidate, emergency: bool) -> str:
        if emergency and best.trajectory.terminal_speed_mps < 0.5:
            return "EMERGENCY_STOP"
        if best.lane_name == "left":
            return "CHANGE_LEFT"
        if best.lane_name == "right":
            return "CHANGE_RIGHT"
        if best.stop_reason in ("red light", "yellow light"):
            return "STOP_SIGNAL"
        if best.stop_reason == "stop sign":
            return "STOP_SIGN"
        if best.stop_reason == "pedestrian near crosswalk":
            return "YIELD_PEDESTRIAN"
        if best.name == "stop":
            return "YIELD"
        if (best.lead is not None
                and best.lead.gap_m < 40.0
                and best.trajectory.terminal_speed_mps < obs.desired_speed_mps - 0.5):
            return "FOLLOW_LEAD"
        turn = next(
            (j.movement for j in obs.junctions
             if j.entry_distance_m < 30.0 and j.exit_distance_m > 0.0),
            None,
        )
        if turn in ("LEFT", "RIGHT"):
            return f"TURN_{turn}"
        return "KEEP_LANE"

    @staticmethod
    def _notes(best: Candidate, candidates: List[Candidate]) -> List[str]:
        notes = []
        if best.stop_reason:
            notes.append(f"stop: {best.stop_reason}")
        elif best.lead is not None:
            notes.append(
                f"lead #{best.lead.actor_id}  "
                f"{best.lead.gap_m:.0f} m  "
                f"{best.lead.speed_mps:.1f} m/s"
            )
        else:
            notes.append("")

        valid_count = sum(c.valid for c in candidates)
        notes.append(
            f"{len(candidates)} candidates, {valid_count} valid "
            f"→ {best.lane_name} {best.name}"
        )
        for c in candidates:
            mark = "*" if c is best else " "
            info = f"{c.cost:.2f}" if c.valid else c.reason
            notes.append(f"{mark}{c.lane_name:7s} {c.name:6s} {info}")

        return notes
