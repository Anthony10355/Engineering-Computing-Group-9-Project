"""
=============================================================================
PROJECT B – AV TRAJECTORY PLANNER
Team 7–12 | Autonomous Driving Challenge
Team members: Anthony Pollard, Cole Pulaski, Will Cunningham, Brandon Debrosse
=============================================================================

Goal: Pass as many scenes generated by Project A (Team 1–6) as possible,
      without crashing, while following US traffic law.

Requirements:
  ✓ Bounded acceleration and speed of ego car
  ✓ Bounded steering wheel angle of ego car
  ✓ Don't crash as much as possible
  ✓ Navigate to the destination
  ✓ Follow US traffic law

Strategy Overview
-----------------
This planner uses a multi-candidate selection approach:

  1.  Every 0.05 s the planner evaluates several candidate trajectories:
        • KEEP_LANE     – stay in the current lane, cruise or follow a lead car
        • CHANGE_LEFT   – move to the left lane if safe and legal
        • CHANGE_RIGHT  – move to the right lane if safe and legal
        • STOP_SIGNAL   – decelerate to a stop at a red / yellow light
        • STOP_SIGN     – decelerate to a stop at a stop sign (wait 2 s)
        • YIELD         – decelerate to yield at an un-signalised junction
        • CONFLICT_STOP – decelerate early when a pedestrian or car will
                          cross our path

  2.  Each candidate is validated against a prediction of every observed
      road user over 8 s: vehicles in our lanes are predicted to follow their
      lane (so curves don't cause false alarms); pedestrians and crossing
      traffic use a constant-velocity prediction with a 1.5 s time buffer.
      Candidates that result in a predicted collision are marked invalid.

  3.  The cheapest valid candidate is chosen.  Cost captures:
        • Progress lost (time penalty for going slower than desired)
        • Unnecessary lane changes (+0.05)
        • Leaving the route lane (+0.10)
        • Harsh braking (+0.05 × |accel| / 3 m/s²)
        • Pedestrian proximity near crosswalks (+0.20 extra caution)

  4.  If no candidate is valid, braking limits are tightened and candidates
      are re-evaluated.  If still none, an emergency full-stop is performed.

  5.  Crosswalk behaviour: when a crosswalk is within 30 m and a pedestrian
      is in our path, walking toward it, or waiting at the kerb, the planner
      yields regardless of signal state.

  6.  Speed and following: cruise at 97 % of the posted limit; follow the
      vehicle ahead that constrains us most (not just the nearest); score lane
      changes on the speed of the target lane so we overtake slow road users.

Constraints hard-coded to match competition rules:
  max_speed    97 % of the posted speed limit
  max_accel    2.0 m/s²    (≈ 0.2 g; the simulator controller's limit)
  max_decel    3.0 m/s²    (≈ 0.30 g, normal)
  max_decel    6.0 m/s²    (emergency only)
  max_jerk     6.0 m/s³
  steering     bounded implicitly through the quintic lateral profile
               (peak lateral accel ≤ 1.8 m/s²  →  |δ| well within ±0.6 rad)
=============================================================================
"""

